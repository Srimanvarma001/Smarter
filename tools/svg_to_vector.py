#!/usr/bin/env python3
"""Convert the chessnut piece SVGs into Android vector drawables.

    python3 tools/svg_to_vector.py <dir with wK.svg ... bP.svg> app/src/main/res/drawable

Handles what those files use: nested <g> with inherited presentation attributes, <path>,
<circle> and <ellipse>, no transforms. Path data is re-serialised with explicit separators,
because older Android path parsers misread compact arc flags such as "a5 5 0 015 5".
"""
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

SVG = "{http://www.w3.org/2000/svg}"
INHERITED = ("fill", "stroke", "stroke-width", "stroke-linecap", "stroke-linejoin", "stroke-miterlimit")
ARG_COUNTS = {"m": 2, "l": 2, "h": 1, "v": 1, "c": 6, "s": 4, "q": 4, "t": 2, "a": 7, "z": 0}
NUMBER = re.compile(r"[+-]?(?:\d+\.?\d*|\.\d+)(?:[eE][+-]?\d+)?")


def normalize_path(d):
    out, i, cmd = [], 0, None
    while i < len(d):
        ch = d[i]
        if ch.isspace() or ch == ",":
            i += 1
            continue
        if ch.isalpha():
            cmd = ch
            out.append(ch)
            i += 1
            if cmd.lower() == "z":
                cmd = None
            continue
        if cmd is None:
            raise ValueError(f"number without command at {i}: {d[i:i + 20]}")
        # Read one full argument group for the current command (implicit repetition allowed).
        args = []
        for n in range(ARG_COUNTS[cmd.lower()]):
            while i < len(d) and (d[i].isspace() or d[i] == ","):
                i += 1
            if cmd.lower() == "a" and n in (3, 4):
                args.append(d[i])  # arc flags are a single 0 or 1
                i += 1
            else:
                m = NUMBER.match(d, i)
                if not m:
                    raise ValueError(f"bad number at {i}: {d[i:i + 20]}")
                args.append(m.group())
                i = m.end()
        out.append(" ".join(args))
        if cmd in "Mm":  # extra pairs after a moveto are linetos
            cmd = "L" if cmd == "M" else "l"
    return " ".join(out)


def color(value):
    if value in (None, "none"):
        return None
    named = {"white": "#FFFFFF", "black": "#000000"}
    value = named.get(value, value)
    if re.fullmatch(r"#[0-9a-fA-F]{3}", value):
        value = "#" + "".join(c * 2 for c in value[1:])
    return value.upper()


def shapes(element, inherited):
    attrs = dict(inherited)
    for key in INHERITED:
        if key in element.attrib:
            attrs[key] = element.attrib[key]
    tag = element.tag.replace(SVG, "")
    if tag == "path":
        yield normalize_path(element.attrib["d"]), attrs
    elif tag in ("circle", "ellipse"):
        cx, cy = float(element.attrib["cx"]), float(element.attrib["cy"])
        rx = float(element.attrib.get("rx", element.attrib.get("r")))
        ry = float(element.attrib.get("ry", element.attrib.get("r")))
        yield (f"M {cx - rx:g} {cy:g} A {rx:g} {ry:g} 0 1 0 {cx + rx:g} {cy:g} "
               f"A {rx:g} {ry:g} 0 1 0 {cx - rx:g} {cy:g} Z"), attrs
    for child in element:
        yield from shapes(child, attrs)


def convert(svg_file):
    root = ET.parse(svg_file).getroot()
    _, _, width, height = root.attrib["viewBox"].split()
    lines = [
        '<?xml version="1.0" encoding="utf-8"?>',
        f"<!-- Generated by tools/svg_to_vector.py from chessnut/{svg_file.name} (Apache 2.0, see NOTICE). -->",
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
        '    android:width="48dp"', '    android:height="48dp"',
        f'    android:viewportWidth="{width}"', f'    android:viewportHeight="{height}">',
    ]
    # SVG's default fill is black; the default stroke is none.
    for d, attrs in shapes(root, {"fill": "#000"}):
        lines.append("    <path")
        fill = color(attrs.get("fill"))
        if fill:
            lines.append(f'        android:fillColor="{fill}"')
        stroke = color(attrs.get("stroke"))
        if stroke:
            lines.append(f'        android:strokeColor="{stroke}"')
            lines.append(f'        android:strokeWidth="{attrs.get("stroke-width", "1")}"')
            if "stroke-linecap" in attrs:
                lines.append(f'        android:strokeLineCap="{attrs["stroke-linecap"]}"')
            if "stroke-linejoin" in attrs:
                lines.append(f'        android:strokeLineJoin="{attrs["stroke-linejoin"]}"')
            if "stroke-miterlimit" in attrs:
                lines.append(f'        android:strokeMiterLimit="{attrs["stroke-miterlimit"]}"')
        lines.append(f'        android:pathData="{d}" />')
    lines.append("</vector>")
    return "\n".join(lines) + "\n"


def main():
    src, dest = Path(sys.argv[1]), Path(sys.argv[2])
    for svg_file in sorted(src.glob("[wb][KQRBNP].svg")):
        name = f"piece_{svg_file.stem[0]}{svg_file.stem[1].lower()}.xml"
        (dest / name).write_text(convert(svg_file))
        print(f"{svg_file.name} -> {name}")


if __name__ == "__main__":
    main()
